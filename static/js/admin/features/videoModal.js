function latestProgressStatusForSid(sid, maxDate) {
  const out = {};
  const sidKey = String(sid || '');
  Object.keys(state.progress || {})
    .filter(d => /^\d{4}-\d{2}-\d{2}$/.test(String(d)) && (!maxDate || String(d) <= String(maxDate)))
    .sort()
    .forEach((dateKey) => {
      const perSid = state.progress?.[dateKey]?.[sidKey];
      if (!perSid || typeof perSid !== 'object') return;
      Object.entries(perSid).forEach(([mid, st]) => {
        const key = String(mid);
        if (key.startsWith('__') || key === 'tests') return;
        out[key] = String(st || 'none');
      });
    });
  return out;
}

function latestAutoAssignStatusForSid(sid, maxDate) {
  const out = {};
  const sidKey = String(sid || '');
  Object.keys(state.progress || {})
    .filter(d => /^\d{4}-\d{2}-\d{2}$/.test(String(d)) && (!maxDate || String(d) <= String(maxDate)))
    .sort()
    .forEach((dateKey) => {
      const perSid = state.progress?.[dateKey]?.[sidKey];
      if (!perSid || typeof perSid !== 'object') return;
      const manualMeta = (perSid[PROGRESS_MANUAL_META_KEY] && typeof perSid[PROGRESS_MANUAL_META_KEY] === 'object')
        ? perSid[PROGRESS_MANUAL_META_KEY]
        : {};
      Object.entries(perSid).forEach(([mid, st]) => {
        const key = String(mid);
        if (key.startsWith('__') || key === 'tests') return;
        const value = String(st || 'none');
        if (value === 'none') {
          if (manualMeta[key]) out[key] = 'none';
          return;
        }
        out[key] = value;
      });
    });
  return out;
}

function applyWatchStatusForAutoAssign(lastStatus, watchByMid) {
  const out = { ...(lastStatus || {}) };
  Object.entries(watchByMid || {}).forEach(([mid, entry]) => {
    const key = String(mid);
    const st = watchAutoState(entry);
    if (st === 'done' && out[key] !== 'none' && out[key] !== 'skip') {
      out[key] = 'done';
    } else if (st === 'interrupted' && !out[key]) {
      out[key] = 'interrupted';
    }
  });
  return out;
}

function blockedMidsForAutoAssign(lastStatus) {
  const blocked = {};
  Object.entries(lastStatus || {}).forEach(([mid, st]) => {
    if (isFinishedVideoProgressStatus(st)) blocked[mid] = true;
  });
  return blocked;
}

function isCourseProgressComplete(curVids, sid, maxDate) {
  const mids = (curVids || [])
    .map(v => String(v?.mid || '').trim())
    .filter(Boolean);
  if (!mids.length) return false;

  const latest = latestProgressStatusForSid(sid, maxDate);
  return mids.every(mid => isFinishedVideoProgressStatus(latest[mid]));
}

