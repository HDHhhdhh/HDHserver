function selectedExtraVideoItems(selectedMids) {
  return (selectedMids || [])
    .map(mid => String(mid || '').trim())
    .filter(Boolean)
    .filter(mid => !activePrimaryVideoMids.has(mid))
    .map(mid => {
      const v = videoByMid(mid);
      if (!v) {
        return { mid, title: '', chapter: '', curriculum: '', subCurriculum: '', label: `알 수 없는 영상 (${mid})` };
      }
      return {
        mid,
        title: String(v.title || '').trim(),
        chapter: String(v.chapter ?? '').trim(),
        curriculum: videoCurriculum(v),
        subCurriculum: videoSubCurriculum(v),
        label: videoRowLabel(v),
      };
    });
}

function extraVideoCandidates(assignedSet) {
  const subject = String(activeExtraSubject || '').trim();
  const sub = String(activeExtraSubCurriculum || '').trim();
  const query = String(activeExtraQuery || '').trim().toLowerCase();

  return (state.videos || [])
    .filter(v => {
      const mid = videoMid(v);
      if (!mid || activePrimaryVideoMids.has(mid)) return false;
      if (subject && videoCurriculum(v) !== subject) return false;
      if (sub && videoSubCurriculum(v) !== sub) return false;
      if (query) {
        const hay = [v.title, v.chapter, v.curriculum, v.subCurriculum].map(x => String(x || '').toLowerCase()).join(' ');
        if (!hay.includes(query)) return false;
      }
      return true;
    })
    .sort((a, b) =>
      Number(assignedSet.has(videoMid(b))) - Number(assignedSet.has(videoMid(a))) ||
      videoCurriculum(a).localeCompare(videoCurriculum(b), 'ko') ||
      videoSubCurriculum(a).localeCompare(videoSubCurriculum(b), 'ko') ||
      byChapterAsc(a, b)
    );
}

function buildExtraVideoNote(items) {
  if (!items.length) return '';
  const lines = items.map(item => {
    const scope = [item.curriculum, item.subCurriculum].filter(Boolean).join(' / ');
    const chapter = item.chapter ? `${item.chapter}차시: ` : '';
    const title = item.title || item.label || item.mid;
    return `- ${scope ? `${scope} / ` : ''}${chapter}${title}`;
  });
  return `[커리 외 영상]\n${lines.join('\n')}`;
}

function replaceGeneratedBlock(notes, prevBlock, nextBlock) {
  const prev = String(notes || '').trimEnd();
  const oldBlock = String(prevBlock || '').trim();
  const newBlock = String(nextBlock || '').trim();
  if (oldBlock && prev.includes(oldBlock)) {
    return prev.replace(oldBlock, newBlock).replace(/\n{3,}/g, '\n\n').trim();
  }
  return newBlock ? (prev ? `${prev}\n\n${newBlock}` : newBlock) : prev;
}

async function patchExtraVideoLogAssignment(today, sid, selectedMids) {
  const items = selectedExtraVideoItems(selectedMids);
  const q = new URLSearchParams({ date: String(today), sid: String(sid) }).toString();
  const { data } = await getJSON(`/api/logs/entry?${q}`);
  const entry = (data?.entry && typeof data.entry === 'object') ? data.entry : {};
  const prevBlock = String(entry.extraVideoAssignmentNote || '').trim();
  const noteBlock = buildExtraVideoNote(items);

  if (!items.length && !prevBlock && !Array.isArray(entry.assignedExtraVideos)) {
    return items;
  }

  const clear = [];
  const patchEntry = { updatedAt: new Date().toISOString() };
  if (items.length) patchEntry.assignedExtraVideos = items;
  else clear.push('assignedExtraVideos');

  if (noteBlock) patchEntry.extraVideoAssignmentNote = noteBlock;
  else clear.push('extraVideoAssignmentNote');

  const prevNotes = String(entry.notes || '').trimEnd();
  const nextNotes = replaceGeneratedBlock(prevNotes, prevBlock, noteBlock);
  const body = {
    date: String(today),
    sid: String(sid),
    entry: patchEntry,
  };

  if (nextNotes.trim() !== prevNotes.trim()) {
    if (nextNotes.trim()) patchEntry.notes = nextNotes.trim();
    else clear.push('notes');
    body.base = { notes: prevNotes.trim() };
  }
  if (clear.length) body.__clear = clear;

  const res = await fetch('/api/logs/patch', {
    method: 'POST',
    headers: CT,
    body: JSON.stringify(body),
  });
  const saved = await res.json().catch(() => ({}));
  if (!res.ok || saved?.ok === false) {
    throw new Error(saved?.error || 'extra video log patch failed');
  }

  if (saved?.entry && typeof saved.entry === 'object') {
    state.logs = state.logs || {};
    state.logs[String(today)] = state.logs[String(today)] || {};
    state.logs[String(today)][String(sid)] = saved.entry;
    window.logs = state.logs;
  }
  return items;
}

