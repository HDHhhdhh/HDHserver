function latestProgressStatusForSid(sid, maxDate) {
  const out = {};
  const sidKey = String(sid || '');
  Object.keys(state.progress || {})
    .filter(d => /^\d{4}-\d{2}-\d{2}$/.test(String(d)) && (!maxDate || String(d) <= String(maxDate)))
    .sort()
    .forEach((dateKey) => {
      const perSid = state.progress?.[dateKey]?.[sidKey];
      if (!perSid || typeof perSid !== 'object') return;
      Object.entries(perSid).forEach(([mid, st]) => {
        const key = String(mid);
        if (key.startsWith('__') || key === 'tests') return;
        out[key] = String(st || 'none');
      });
    });
  return out;
}

function isCourseProgressComplete(curVids, sid, maxDate) {
  const mids = (curVids || [])
    .map(v => String(v?.mid || '').trim())
    .filter(Boolean);
  if (!mids.length) return false;

  const latest = latestProgressStatusForSid(sid, maxDate);
  return mids.every(mid => latest[mid] === 'done');
}

