const chapNum = v => {
  const c = (v?.chapter ?? 0);
  const n = Number(c);
  return Number.isNaN(n)
    ? parseFloat(String(c).replace(/[^0-9.]/g, '')) || 0
    : n;
};

const byChapterAsc = (a, b) =>
  chapNum(a) - chapNum(b) ||
  String(a.title || '').localeCompare(String(b.title || ''), 'ko') ||
  String(a.mid).localeCompare(String(b.mid));

function videoMid(v) {
  return String(v?.mid || v?.id || '').trim();
}

function videoCurriculum(v) {
  return String(v?.curriculum || '').trim();
}

function videoSubCurriculum(v) {
  return String(v?.subCurriculum || '').trim();
}

function isTrainingPackVideo(v) {
  return videoSubCurriculum(v).toLowerCase() === TRAINING_PACK_SUBCURRICULUM.toLowerCase();
}

function videoByMid(mid) {
  const key = String(mid || '').trim();
  if (!key) return null;
  return (state.videos || []).find(v => videoMid(v) === key) || null;
}

function uniqueSorted(values) {
  return Array.from(new Set((values || []).map(v => String(v || '').trim()).filter(Boolean)))
    .sort((a, b) => a.localeCompare(b, 'ko'));
}

function extraSubjectOptions() {
  return uniqueSorted((state.videos || []).map(videoCurriculum));
}

function extraSubCurriculumOptions(subject) {
  const subjectKey = String(subject || '').trim();
  return uniqueSorted(
    (state.videos || [])
      .filter(v => !subjectKey || videoCurriculum(v) === subjectKey)
      .map(videoSubCurriculum)
  );
}

