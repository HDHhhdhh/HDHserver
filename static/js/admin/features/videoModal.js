/* ───────────── 공통 fetch helpers ───────────── */
async function getJSON(url) {
  const res = await fetch(url, { cache: 'no-store' });
  let data = null;
  try { data = await res.json(); } catch {}
  return { res, data };
}

function unwrapOkPayload(data, keyHint) {
  if (!data || typeof data !== 'object') return null;

  if (data.ok === true) {
    if (keyHint && data[keyHint] && typeof data[keyHint] === 'object') return data[keyHint];
    const cloned = { ...data };
    delete cloned.ok;
    delete cloned.error;
    return cloned;
  }
  return data;
}

/* ───────────── 최소 hydrate (결석 제외) ───────────── */
async function hydrateUpdates() {
  try {
    const { res, data } = await getJSON('/api/updates');
    if (!res.ok) return false;

    const obj = unwrapOkPayload(data, 'updates');
    if (obj && typeof obj === 'object') {
      state.updates = obj;
      return true;
    }
    return false;
  } catch {
    return false;
  }
}

async function hydrateLogsEntry(today, sid) {
  // 있으면 사용, 없으면 무시
  try {
    const q = new URLSearchParams({ date: String(today), sid: String(sid) }).toString();
    const { res, data } = await getJSON(`/api/logs/entry?${q}`);
    if (!res.ok) return false;

    const entry = (data?.ok === true)
      ? (data.entry && typeof data.entry === 'object' ? data.entry : {})
      : (data && typeof data === 'object' ? data : {});

    state.logs = state.logs || {};
    state.logs[today] = state.logs[today] || {};
    state.logs[today][String(sid)] = entry;
    return true;
  } catch {
    return false;
  }
}

async function hydrateExtraAttend(today) {
  // 있으면 사용, 없으면 무시
  const candidates = ['/api/extra-attend', '/api/extra', '/api/extra_attend', '/api/extra-attend/all'];
  for (const url of candidates) {
    try {
      const { res, data } = await getJSON(url);
      if (!res.ok) continue;

      const obj = unwrapOkPayload(data, 'extra') || unwrapOkPayload(data, 'data') || data;
      if (obj && typeof obj === 'object') {
        state.extra = obj;
        if (!Array.isArray(state.extra[today])) state.extra[today] = state.extra[today] || [];
        return true;
      }
    } catch {}
  }
  return false;
}

async function hydrateProgressMaybe() {
  try {
    if (state.progress && typeof state.progress === 'object' && Object.keys(state.progress).length) return true;

    const { res, data } = await getJSON('/api/progress');
    if (!res.ok) return false;

    const obj = unwrapOkPayload(data, 'progress') || unwrapOkPayload(data, 'data') || data;
    if (obj && typeof obj === 'object') {
      state.progress = obj;
      return true;
    }
    return false;
  } catch {
    return false;
  }
}

async function hydrateForVideoModal(today, sid) {
  await Promise.allSettled([
    hydrateUpdates(),
    hydrateLogsEntry(today, sid),
    hydrateExtraAttend(today),
    hydrateProgressMaybe(),
  ]);
}

/* ───────────── 챕터 정렬 ───────────── */
const chapNum = v => {
  const c = (v?.chapter ?? 0);
  const n = Number(c);
  return Number.isNaN(n)
    ? parseFloat(String(c).replace(/[^0-9.]/g, '')) || 0
    : n;
};

const byChapterAsc = (a, b) =>
  chapNum(a) - chapNum(b) ||
  String(a.title || '').localeCompare(String(b.title || ''), 'ko') ||
  String(a.mid).localeCompare(String(b.mid));

function videoMid(v) {
  return String(v?.mid || v?.id || '').trim();
}

function videoCurriculum(v) {
  return String(v?.curriculum || '').trim();
}

function videoSubCurriculum(v) {
  return String(v?.subCurriculum || '').trim();
}

function videoByMid(mid) {
  const key = String(mid || '').trim();
  if (!key) return null;
  return (state.videos || []).find(v => videoMid(v) === key) || null;
}

function uniqueSorted(values) {
  return Array.from(new Set((values || []).map(v => String(v || '').trim()).filter(Boolean)))
    .sort((a, b) => a.localeCompare(b, 'ko'));
}

function extraSubjectOptions() {
  return uniqueSorted((state.videos || []).map(videoCurriculum));
}

function extraSubCurriculumOptions(subject) {
  const subjectKey = String(subject || '').trim();
  return uniqueSorted(
    (state.videos || [])
      .filter(v => !subjectKey || videoCurriculum(v) === subjectKey)
      .map(videoSubCurriculum)
  );
}

function ensureExtraVideoFilters(stu) {
  const subjects = extraSubjectOptions();
  const stuSubject = String(stu?.curriculum || '').trim();
  if (!activeExtraSubject || !subjects.includes(activeExtraSubject)) {
    activeExtraSubject = subjects.includes(stuSubject) ? stuSubject : (subjects[0] || '');
  }

  const subs = extraSubCurriculumOptions(activeExtraSubject);
  if (activeExtraSubCurriculum && !subs.includes(activeExtraSubCurriculum)) {
    activeExtraSubCurriculum = '';
  }
}

function videoRowLabel(v) {
  const chapter = String(v?.chapter ?? '').trim();
  const title = String(v?.title || videoMid(v) || '영상').trim();
  return chapter ? `${chapter}. ${title}` : title;
}

function videoExtraMeta(v) {
  return [videoCurriculum(v), videoSubCurriculum(v)].filter(Boolean).join(' · ');
}

function renderVideoCheckbox(v, assignedSet, extra = false) {
  const mid = videoMid(v);
  if (!mid) return '';
  const checked = assignedSet.has(mid);
  const meta = extra ? `<span class="vid-extra-meta">${escapeHtml(videoExtraMeta(v))}</span>` : '';
  return `
    <label class="vid-row${extra ? ' vid-extra-row' : ''}${checked ? ' is-selected' : ''}">
      <input type="checkbox" value="${escapeHtml(mid)}" ${checked ? 'checked' : ''}>
      ${escapeHtml(videoRowLabel(v))}${meta}
    </label>
  `;
}

