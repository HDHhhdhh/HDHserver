export function initVideoModal() {
  ensureModal();

  const vidModal = $('vidModal');
  const mTitle = $('mTitle');
  const chkZone = $('chkZone');
  const mSave = $('mSave');
  const mSaveStatus = $('mSaveStatus');

  function setSaveStatus(message = '', isError = false) {
    if (!mSaveStatus) return;
    mSaveStatus.textContent = message;
    mSaveStatus.classList.toggle('is-error', !!isError);
  }

  async function openVideoModalForRow(rowOrButton, opts = {}) {
    setSaveStatus('');
    const tr = rowOrButton?.closest?.('tr[data-sid]') || rowOrButton;
    editingSid = tr?.dataset?.sid;
    const stu = state.students.find(x => String(x.id) === String(editingSid));
    if (!stu) { alert('학생 정보를 찾을 수 없습니다.'); return; }

    const today = todayLocalKey();

    // ✅ 결석 관련 fetch 없음. 필요한 것만 hydrate.
    await hydrateForVideoModal(today, editingSid);

    mTitle.textContent = `${stu.name} – ${stu.curriculum} (${stu.subCurriculum || '전체'})`;
    renderAutoAssignControl(stu);

    const curKey = (stu.curriculum || '').trim().toLowerCase();
    const subKey = (stu.subCurriculum || '').trim().toLowerCase();

    // ① 과목+소과목 필터
    let curVids = (state.videos || [])
      .filter(v =>
        String(v.curriculum || '').trim().toLowerCase() === curKey &&
        String(v.subCurriculum || '').trim().toLowerCase() === subKey
      )
      .slice()
      .sort(byChapterAsc);

    // fallback: 소과목 안 맞으면 과목만
    if (!curVids.length) {
      curVids = (state.videos || [])
        .filter(v => String(v.curriculum || '').trim().toLowerCase() === curKey)
        .slice()
        .sort(byChapterAsc);
    }

    let assigned = readAssignFor(state.updates, today, editingSid);
    const hadAssignedOnOpen = assigned.length > 0;

    // ✅ 자동배정 허용 조건: "오늘 학생 표(오늘 수업 대상)"인 경우에만
    const allowAutoAssign = isTodayStudent(stu);

    // ② 기본 자동 추천 (비어 있을 때만) + 오늘 수업 대상일 때만
    activeVideoList = curVids;
    activeAllowAutoAssign = allowAutoAssign;
    activeBlockedMids = {};
    activeAutoGenerated = false;

    if (assigned.length === 0 && allowAutoAssign) {
      const lastStatus = {};
      const datesAsc = Object.keys(state.progress || {}).sort();
      for (const d of datesAsc) {
        const perSid = state.progress[d]?.[editingSid];
        if (!perSid) continue;
        for (const [mid, st] of Object.entries(perSid)) {
          if (String(mid).startsWith('__') || mid === 'tests') continue;
          lastStatus[mid] = st;
        }
      }

      const blocked = {};
      for (const [mid, st] of Object.entries(lastStatus)) {
        if (st === 'done' || st === 'skip') blocked[mid] = true;
      }

      activeBlockedMids = blocked;

      const toAssign = pickAutoVideos(curVids, blocked, autoAssignCountForStudent(stu));

      assigned = toAssign;
      activeAutoGenerated = !hadAssignedOnOpen;

      // ✅ 배열 포맷으로 저장
      state.updates = state.updates || {};
      writeAssignFor(state.updates, today, editingSid, assigned);
      fetch('/api/updates/patch', {
        method: 'POST',
        headers: CT,
        body: JSON.stringify({ date: today, sid: String(editingSid), videos: assigned })
      }).catch(() => {});
    }

    // ③ 체크박스 렌더
    const note = (!allowAutoAssign && assigned.length === 0)
      ? `<div style="margin:0 0 8px 0;padding:8px 10px;border-radius:10px;background:rgba(59,130,246,.12);font-size:12px;line-height:1.35">
           자동배정은 <b>오늘 학생 표(오늘 수업 대상)</b>일 때만 작동합니다. (지금은 자동배정 안 함)
         </div>`
      : '';

    chkZone.innerHTML = curVids.length
      ? note + curVids.map(v => `
        <label style="display:block;user-select:none;cursor:pointer">
          <input type="checkbox" value="${escapeHtml(v.mid)}"
            ${assigned.includes(String(v.mid)) ? 'checked' : ''}>
          ${escapeHtml(v.chapter)}. ${escapeHtml(v.title)}
        </label>
      `).join('')
      : `<div style="padding:6px 4px;color:#666;font-size:13px">
          해당 과목 영상이 없습니다.
        </div>`;

    if (opts.layout === 'student-work') syncStudentPopupLayoutVars();
    vidModal.classList.toggle('student-work-layout', opts.layout === 'student-work');
    vidModal.style.display = 'flex';
    requestAnimationFrame(scrollVideoPopupToFirstChecked);
  }

  window.openVideoAssignmentPopupForRow = openVideoModalForRow;
  window.closeVideoAssignmentPopup = () => {
    vidModal.style.display = 'none';
    vidModal.classList.remove('student-work-layout');
    if (!document.querySelector('#logModal.student-work-layout')) hideStudentPopupScrim();
  };

  window.showStudentPopupBackdrop = showStudentPopupScrim;
  window.hideStudentPopupBackdrop = hideStudentPopupScrim;

  document.body.addEventListener('click', async (e) => {
    const btn = e.target.closest('.editVid');
    if (!btn) return;
    await openVideoModalForRow(btn);
  });

  vidModal.addEventListener('click', async (e) => {
    const btn = e.target.closest('.auto-count-btn');
    if (!btn) return;
    e.preventDefault();
    try {
      await saveAutoAssignCountForCurrent(btn.dataset.count);
    } catch (err) {
      console.error(err);
      toast('자동 배정 영상 수 저장 실패');
    }
  });

  /* ───────────── 드래그 다중 선택 ───────────── */
  let pointerDown = false;
  let dragActive = false;
  let dragCheckValue = null;
  let startCheckbox = null;
  let startChecked = false;
  let suppressClickOnce = false;

  function findCheckboxFromEventTarget(target) {
    const label = target.closest('label');
    if (!label) return null;
    return label.querySelector('input[type="checkbox"]');
  }

  chkZone.addEventListener('mousedown', (e) => {
    if (e.button !== 0) return;
    const cb = findCheckboxFromEventTarget(e.target);
    if (!cb) return;

    pointerDown = true;
    dragActive = false;
    dragCheckValue = null;
    startCheckbox = cb;
    startChecked = cb.checked;
  });

  chkZone.addEventListener('mousemove', (e) => {
    if (!pointerDown) return;
    const cb = findCheckboxFromEventTarget(e.target);
    if (!cb) return;

    if (!dragActive) {
      dragActive = true;
      dragCheckValue = !startChecked;
      if (startCheckbox) startCheckbox.checked = dragCheckValue;
    }

    cb.checked = dragCheckValue;
    e.preventDefault();
  });

  chkZone.addEventListener('mouseover', (e) => {
    if (!pointerDown) return;
    const cb = findCheckboxFromEventTarget(e.target);
    if (!cb) return;

    if (!dragActive) {
      dragActive = true;
      dragCheckValue = !startChecked;
      if (startCheckbox) startCheckbox.checked = dragCheckValue;
    }

    cb.checked = dragCheckValue;
    e.preventDefault();
  });

  chkZone.addEventListener('click', (e) => {
    if (!suppressClickOnce) return;
    const cb = findCheckboxFromEventTarget(e.target);
    if (!cb) return;
    e.preventDefault();
    e.stopPropagation();
    suppressClickOnce = false;
  });

  document.addEventListener('mouseup', () => {
    if (!pointerDown) return;
    pointerDown = false;
    if (dragActive) suppressClickOnce = true;

    dragActive = false;
    dragCheckValue = null;
    startCheckbox = null;
  });

  /* ───────────── 저장 ───────────── */
  mSave.onclick = () => {
    setSaveStatus('');
    mSave.disabled = true;
    const today = todayLocalKey();
    const selected = Array.from(
      document.querySelectorAll('#chkZone input[type="checkbox"]:checked')
    ).map(b => String(b.value));

    state.updates = state.updates || {};

    if (selected.length) {
      writeAssignFor(state.updates, today, editingSid, selected);
    } else {
      state.updates[today] = state.updates[today] || {};
      delete state.updates[today][String(editingSid)];
    }

    fetch('/api/updates/patch', {
      method: 'POST',
      headers: CT,
      body: JSON.stringify(selected.length
        ? { date: today, sid: String(editingSid), videos: selected }
        : { date: today, sid: String(editingSid), remove: true })
    })
      .then(() => fetch('/api/updates', { cache: 'no-store' }))
      .then(r => r.json())
      .then(u => {
        const obj = unwrapOkPayload(u, 'updates') || u;
        if (obj && typeof obj === 'object') state.updates = obj;
        setSaveStatus('저장 완료');
        document.dispatchEvent(new CustomEvent('admin:refresh'));
      })
      .catch(() => setSaveStatus('저장 실패', true))
      .finally(() => {
        mSave.disabled = false;
      });
  };
}
