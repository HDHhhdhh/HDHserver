function sameStringSet(left, right) {
  const a = new Set((left || []).map(String));
  const b = new Set((right || []).map(String));
  return a.size === b.size && Array.from(a).every(value => b.has(value));
}

function nonReviewSelectionChanged(selected) {
  const selectedNonReview = (selected || []).filter(mid => !activeRegisteredReviewMids.has(String(mid)));
  const initialNonReview = Array.from(activeInitialAssignedMids)
    .filter(mid => !activeRegisteredReviewMids.has(String(mid)));
  return !sameStringSet(selectedNonReview, initialNonReview);
}

function shouldSkipForLow(student, video) {
  if (!student || student.level !== '하') return false;
  const ex = video?.exNum;
  if (!ex || typeof ex !== 'object') return false;
  return Number(ex['하']) === 0;
}

function pickAutoVideos(curVids, blocked, count, student = null) {
  const parsedCount = Number(count);
  const maxAssign = Number.isFinite(parsedCount)
    ? Math.max(MIN_AUTO_ASSIGN_COUNT, Math.min(MAX_EFFECTIVE_AUTO_ASSIGN_COUNT, Math.round(parsedCount)))
    : DEFAULT_AUTO_ASSIGN_COUNT;
  const picked = [];
  for (const v of curVids || []) {
    const mid = String(v?.mid || '').trim();
    if (!mid) continue;
    if (blocked?.[mid]) continue;
    if (shouldSkipForLow(student, v)) continue;
    picked.push(mid);
    if (picked.length >= maxAssign) break;
  }
  return picked;
}

function watchRatio(entry) {
  const last = Number(entry?.last || 0);
  const dur = Number(entry?.dur || 0);
  if (!Number.isFinite(last) || !Number.isFinite(dur) || dur <= 0) return 0;
  return Math.max(0, Math.min(1, last / dur));
}

function watchAutoState(entry) {
  if (!entry || typeof entry !== 'object') return '';
  if (entry.completed || watchRatio(entry) >= WATCH_DONE_RATIO) return 'done';
  if (watchRatio(entry) >= WATCH_INTERRUPTED_RATIO) return 'interrupted';
  return '';
}

function isFinishedVideoProgressStatus(status) {
  return VIDEO_PROGRESS_FINISHED_STATUSES.has(String(status || '').trim());
}

async function fetchLatestWatchForSid(sid) {
  const key = String(sid || '').trim();
  if (!key) return {};
  try {
    const params = new URLSearchParams({ sid: key });
    const res = await fetch(`/api/watch/latest?${params.toString()}`, { cache: 'no-store' });
    if (!res.ok) return {};
    const payload = await res.json();
    return (payload && typeof payload.watch === 'object') ? payload.watch : {};
  } catch {
    return {};
  }
}

