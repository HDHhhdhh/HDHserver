function readAssignValueFor(updates, day, sid) {
  const dmap = updates?.[day] || {};
  const k1 = String(sid);
  const k2 = Number.isFinite(+sid) ? String(+sid) : null;
  return dmap[k1] ?? (k2 != null ? dmap[k2] : undefined);
}

function readAssignFor(updates, day, sid) {
  const raw = readAssignValueFor(updates, day, sid);

  if (Array.isArray(raw)) return raw.map(String);
  if (raw && Array.isArray(raw.videos)) return raw.videos.map(String);
  return [];
}

function isManualVideoAssignment(value) {
  return !!(
    value &&
    typeof value === 'object' &&
    !Array.isArray(value) &&
    (value.source === 'manual' || value.manual === true || value.manualVideoAssign === true)
  );
}

function writeAssignFor(updates, day, sid, arr, source = 'auto') {
  const k = String(sid);
  updates[day] = updates[day] || {};
  const dmap = updates[day];

  const numKey = Number.isFinite(+sid) ? String(+sid) : null;
  if (numKey && numKey !== k && dmap[numKey] !== undefined) delete dmap[numKey];

  dmap[k] = {
    videos: arr.map(String),
    source: source === 'manual' ? 'manual' : 'auto',
  };
}

function pickAutoVideos(curVids, blocked, count) {
  const maxAssign = clampAutoAssignCount(count);
  const picked = [];
  for (const v of curVids || []) {
    const mid = String(v?.mid || '').trim();
    if (!mid) continue;
    if (blocked?.[mid]) continue;
    picked.push(mid);
    if (picked.length >= maxAssign) break;
  }
  return picked;
}

function watchRatio(entry) {
  const last = Number(entry?.last || 0);
  const dur = Number(entry?.dur || 0);
  if (!Number.isFinite(last) || !Number.isFinite(dur) || dur <= 0) return 0;
  return Math.max(0, Math.min(1, last / dur));
}

function watchAutoState(entry) {
  if (!entry || typeof entry !== 'object') return '';
  if (entry.completed || watchRatio(entry) >= WATCH_DONE_RATIO) return 'done';
  if (watchRatio(entry) >= WATCH_INTERRUPTED_RATIO) return 'interrupted';
  return '';
}

async function fetchLatestWatchForSid(sid) {
  const key = String(sid || '').trim();
  if (!key) return {};
  try {
    const params = new URLSearchParams({ sid: key });
    const res = await fetch(`/api/watch/latest?${params.toString()}`, { cache: 'no-store' });
    if (!res.ok) return {};
    const payload = await res.json();
    return (payload && typeof payload.watch === 'object') ? payload.watch : {};
  } catch {
    return {};
  }
}

