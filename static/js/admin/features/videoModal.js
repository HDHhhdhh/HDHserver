async function saveAutoAssignCountForCurrent(count) {
  const sid = String(editingSid || '').trim();
  if (!sid) return;

  const stu = state.students.find(x => String(x.id) === sid);
  if (!stu) return;

  const nextCount = clampAutoAssignCount(count);

  stu[AUTO_ASSIGN_FIELD] = nextCount;
  renderAutoAssignControl(stu);

  const res = await fetch('/api/update', {
    method: 'POST',
    headers: CT,
    body: JSON.stringify({ id: sid, field: AUTO_ASSIGN_FIELD, value: nextCount })
  });
  if (!res.ok) throw new Error('auto assign count save failed');

  if (!activeAllowAutoAssign || !activeAutoGenerated) return;

  const today = editingVideoDate || getAdminDate();
  const assigned = pickAutoVideos(
    activeVideoList,
    activeBlockedMids,
    effectiveAutoAssignCountForStudent(stu, today),
    stu,
  );
  const preservedReviewMids = Array.from(activeRegisteredReviewMids);
  const preservedTrainingPackMids = Array.from(activeRegisteredTrainingPackMids);
  const preservedStudentTrainingPackMids = Array.from(activeStudentTrainingPackMids);
  const nextAssigned = Array.from(new Set([
    ...assigned,
    ...preservedReviewMids,
    ...preservedTrainingPackMids,
  ]));
  setCheckedMids(nextAssigned);

  state.updates = state.updates || {};
  writeAssignFor(
    state.updates,
    today,
    sid,
    nextAssigned,
    'auto',
    preservedReviewMids,
    preservedTrainingPackMids,
    preservedStudentTrainingPackMids,
  );
  await fetch('/api/updates/patch', {
    method: 'POST',
    headers: CT,
    body: JSON.stringify({
      date: today,
      sid,
      entry: {
        videos: nextAssigned,
        source: 'auto',
        reviewVideos: preservedReviewMids,
        trainingPackVideos: preservedTrainingPackMids,
        studentTrainingPackVideos: preservedStudentTrainingPackMids,
      },
    })
  });
  activeAssignmentManual = false;
  activeVideoSelectionDirty = false;
}

/* ───────────── 오늘 학생 표(오늘 수업 대상) 판정 ───────────── */
/** today.js의 computeTodayList와 동일 기준(결석/완료/정규/보강) */
function isTodayStudent(stu, dateKey = getAdminDate()) {
  if (!stu) return false;

  const today = dateKey || getAdminDate();
  const WCHR = '일월화수목금토';
  const wchr = WCHR[new Date(today).getDay()];
  const sid = String(stu.id ?? '');
  if (!sid) return false;

  const hasWeekday = (s, w) => studentScheduleValues(s).some(v => String(v).startsWith(w));

  // ✅ 결석 제외: 영상 모달은 state.absentByDate를 "읽기만" 한다
  const absentByDate = (state.absentByDate && typeof state.absentByDate === 'object') ? state.absentByDate : {};
  const absentSet = new Set((absentByDate[today] || []).map(String));
  if (absentSet.has(sid)) return false;

  // ✅ 오늘 done:true 제외
  const logsToday = (state.logs && state.logs[today]) ? state.logs[today] : {};
  const logEntry = logsToday?.[sid] || {};
  if (logEntry?.done === true) return false;
  if (Object.prototype.hasOwnProperty.call(logEntry, 'selfStudy')) {
    return !(logEntry.selfStudy === true || logEntry.selfStudy === 'true' || logEntry.selfStudy === 1 || logEntry.selfStudy === '1');
  }
  if (isSelfStudyScheduledForDate(stu, today)) return false;

  // 정규 등원 or 보강이면 포함
  const regular = hasWeekday(stu, wchr);

  const extra = state.extra || {};
  const extraIds = Array.isArray(extra[today]) ? extra[today].map(String) : [];
  const isExtra = extraIds.includes(sid);

  return regular || isExtra;
}

