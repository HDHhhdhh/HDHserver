function positiveFiniteNumber(value) {
  const n = Number(value);
  return Number.isFinite(n) && n > 0 ? n : 0;
}

function zoomedOutViewportScale() {
  const innerWidth = positiveFiniteNumber(window.innerWidth);
  if (!innerWidth) return 1;

  // Chrome zoom-out grows innerWidth while outer/screen widths stay near the physical window.
  const referenceWidth = Math.max(
    positiveFiniteNumber(window.outerWidth),
    positiveFiniteNumber(window.screen?.availWidth),
    positiveFiniteNumber(window.screen?.width)
  );
  if (!referenceWidth) return 1;

  return Math.max(1, Math.min(STUDENT_POPUP_MAX_SCALE, innerWidth / referenceWidth));
}

function clampAutoAssignCount(value, fallback = DEFAULT_AUTO_ASSIGN_COUNT) {
  const n = Number(value);
  if (!Number.isFinite(n)) return fallback;
  return Math.max(MIN_AUTO_ASSIGN_COUNT, Math.min(MAX_AUTO_ASSIGN_COUNT, Math.round(n)));
}

function isAbleCurriculumValue(value) {
  return String(value ?? '').trim().toLowerCase() === ABLE_CURRICULUM_KEY;
}

function usesAbleCurriculum(stu) {
  return isAbleCurriculumValue(stu?.curriculum) || isAbleCurriculumValue(stu?.subCurriculum);
}

function defaultAutoAssignCountForStudent(stu) {
  return usesAbleCurriculum(stu) ? ABLE_AUTO_ASSIGN_COUNT : DEFAULT_AUTO_ASSIGN_COUNT;
}

function autoAssignCountForStudent(stu) {
  return clampAutoAssignCount(stu?.[AUTO_ASSIGN_FIELD], defaultAutoAssignCountForStudent(stu));
}

function studentScheduleValues(stu) {
  return Object.keys(stu || {})
    .filter(key => /^day\d+$/.test(key) && stu[key])
    .sort((a, b) => Number(a.slice(3)) - Number(b.slice(3)))
    .map(key => String(stu[key]));
}

function weekdayCharForDate(dateKey) {
  const match = /^(\d{4})-(\d{2})-(\d{2})$/.exec(String(dateKey || '').trim());
  if (!match) return '';
  const date = new Date(Number(match[1]), Number(match[2]) - 1, Number(match[3]));
  return '일월화수목금토'[date.getDay()] || '';
}

function scheduledSlotsForDate(stu, dateKey) {
  const override = state.weekendSlots?.[dateKey]?.[String(stu?.id || '')];
  if (override !== undefined && override !== null) {
    const overrideSlots = (Array.isArray(override) ? override : [override])
      .map(value => Number(value))
      .filter(value => Number.isInteger(value) && value >= 1 && value <= 6);
    if (overrideSlots.length) return Array.from(new Set(overrideSlots)).sort((a, b) => a - b);
  }

  const weekday = weekdayCharForDate(dateKey);
  if (!weekday) return [];

  const slotPattern = new RegExp(`${weekday}\\s*([1-6])(?!\\d|:)`, 'g');
  const slots = studentScheduleValues(stu).flatMap(value =>
    Array.from(value.matchAll(slotPattern), match => Number(match[1]))
  );
  return Array.from(new Set(slots)).sort((a, b) => a - b);
}

function hasConsecutiveClassesForDate(stu, dateKey) {
  const slots = scheduledSlotsForDate(stu, dateKey);
  return slots.some((slot, index) => index > 0 && slot === slots[index - 1] + 1);
}

function effectiveAutoAssignCountForStudent(stu, dateKey) {
  const configured = autoAssignCountForStudent(stu);
  return hasConsecutiveClassesForDate(stu, dateKey)
    ? configured * 2
    : configured;
}

function escapeHtml(s) {
  return String(s ?? '')
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;');
}

